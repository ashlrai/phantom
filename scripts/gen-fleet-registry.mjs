import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// An optional source directory lets regression tests check isolated CLI fixtures.
export function generateFleetRegistry(args) {
  const cli = resolve(args.find(arg => arg !== '--check') ?? fileURLToPath(new URL('../src/cli', import.meta.url)));
  const target = resolve(cli, 'fleet-subcommand-registry.ts');
  const verbs = readdirSync(cli).filter(file => /^fleet-.*\.ts$/.test(file)).flatMap(file => {
    const verb = file.slice('fleet-'.length, -3);
    // Keep exactly the naming and PascalCase rules in fleet-subcommand-resolve.ts.
    if (verb.length < 2 || verb.length > 40 || !/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(verb)) return [];
    const exportName = 'cmdFleet' + verb.split('-').map(part => part[0].toUpperCase() + part.slice(1)).join('');
    return new RegExp(`\\bexport\\s+async\\s+function\\s+${exportName}\\s*\\(`).test(readFileSync(resolve(cli, file), 'utf8')) ? [verb] : [];
  }).sort();
  const output = '// generated by scripts/gen-fleet-registry.mjs; run it after adding a verb\n'
    + 'export const FLEET_SUBCOMMAND_LOADERS: Record<string, () => Promise<Record<string, unknown>>> = {\n'
    + verbs.map(verb => `  '${verb}': () => import('./fleet-${verb}.js'),\n`).join('') + '};\n';
  if (args.includes('--check')) {
    if (readFileSync(target, 'utf8') !== output) {
      console.error('Fleet subcommand registry is out of sync; run node scripts/gen-fleet-registry.mjs');
      return 1;
    }
  } else {
    writeFileSync(target, output);
  }
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = generateFleetRegistry(process.argv.slice(2));
}
