/**
 * scripts/lib/docs-pages.mjs: shared, dependency-free docs page model.
 *
 * One definition of "a docs page" for the llms.txt generator, the site build
 * that serves every page as Markdown, and the read-only docs MCP server
 * (`phm mcp docs`). Everything here is local filesystem only: no network,
 * no credentials, no model calls. Output is deterministic for a given tree.
 */
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

export const DOCS_SITE_ORIGIN = 'https://verse.ashlr.ai';
/** Directories under docs/ that are not public documentation (internal audits and scratch notes). */
export const EXCLUDED_DOC_DIRS = Object.freeze(['internal']);
export const INDEX_START = '<!-- docs-index:start (generated by scripts/generate-docs-llms.mjs; do not edit) -->';
export const INDEX_END = '<!-- docs-index:end -->';
const MAX_PAGE_BYTES = 2 * 1024 * 1024;
const SLUG_PATTERN = /^[A-Za-z0-9][A-Za-z0-9._-]*(\/[A-Za-z0-9][A-Za-z0-9._-]*)*$/;

function* markdownFiles(dir, rel = '') {
  const entries = readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  for (const entry of entries) {
    const next = rel ? `${rel}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      if (!rel && EXCLUDED_DOC_DIRS.includes(entry.name)) continue;
      yield* markdownFiles(join(dir, entry.name), next);
    } else if (entry.isFile() && entry.name.endsWith('.md')) {
      yield next;
    }
  }
}

function plain(text) {
  return text
    .replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1')
    .replace(/[`*_]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/** Title is the first H1 outside code fences; description is the first prose line after it. */
export function summarizeMarkdown(text, fallbackTitle) {
  let title = null;
  let description = '';
  let fenced = false;
  for (const raw of text.split('\n')) {
    const line = raw.trim();
    if (line.startsWith('```') || line.startsWith('~~~')) { fenced = !fenced; continue; }
    if (fenced) continue;
    if (title === null) {
      const h1 = line.match(/^#\s+(.+)$/);
      if (h1) title = plain(h1[1]);
      continue;
    }
    if (!line || /^(#|>|\||-{3,}|[-*+]\s|\d+\.\s|<|!?\[[^\]]*\]:)/.test(line)) {
      if (description) break;
      continue;
    }
    description += `${description ? ' ' : ''}${plain(line)}`;
    if (/[.!?]$/.test(description) || description.length > 200) break;
  }
  if (description.length > 180) description = `${description.slice(0, 177).trimEnd()}...`;
  return { title: title || fallbackTitle, description };
}

/** Every public docs page, sorted by slug. `slug` is the path under docs/ without `.md`. */
export function listDocsPages(docsDir) {
  return [...markdownFiles(docsDir)].map((file) => {
    const slug = file.slice(0, -3);
    const text = readFileSync(join(docsDir, ...file.split('/')), 'utf8');
    const { title, description } = summarizeMarkdown(text, slug);
    return { slug, file: `docs/${file}`, title, description, bytes: Buffer.byteLength(text, 'utf8') };
  });
}

export function isSafeSlug(slug) {
  return typeof slug === 'string' && slug.length <= 200 && SLUG_PATTERN.test(slug) && !slug.split('/').includes('..');
}

export function docsPageUrl(slug) {
  return `${DOCS_SITE_ORIGIN}/docs/${slug}.md`;
}

/**
 * Read one page by slug. Only slugs that name a listed page resolve, so a
 * crafted slug can never reach outside docs/ (or into an excluded directory).
 * Returns null when the page does not exist.
 */
export function readDocsPage(docsDir, slug) {
  if (!isSafeSlug(slug)) return null;
  const clean = slug.endsWith('.md') ? slug.slice(0, -3) : slug;
  const page = listDocsPages(docsDir).find((p) => p.slug === clean);
  if (!page) return null;
  const text = readFileSync(join(docsDir, ...`${clean}.md`.split('/')), 'utf8');
  return { ...page, text: Buffer.byteLength(text, 'utf8') > MAX_PAGE_BYTES ? text.slice(0, MAX_PAGE_BYTES) : text };
}

function terms(query) {
  return String(query).toLowerCase().split(/[^a-z0-9_.-]+/).filter((t) => t.length > 1).slice(0, 12);
}

/**
 * Lexical search over titles, slugs and bodies. Title hits outweigh slug hits,
 * which outweigh body hits; ties break by slug so results are stable.
 */
export function searchDocsPages(docsDir, query, limit = 10) {
  const wanted = terms(query);
  if (wanted.length === 0) return [];
  const results = [];
  for (const page of listDocsPages(docsDir)) {
    const body = readFileSync(join(docsDir, ...`${page.slug}.md`.split('/')), 'utf8').toLowerCase();
    const title = page.title.toLowerCase();
    const slug = page.slug.toLowerCase();
    let score = 0;
    for (const term of wanted) {
      if (title.includes(term)) score += 10;
      if (slug.includes(term)) score += 5;
      const first = body.indexOf(term);
      if (first >= 0) {
        score += 1 + Math.min(4, body.split(term).length - 2);
      }
    }
    if (score === 0) continue;
    const at = wanted.map((t) => body.indexOf(t)).filter((i) => i >= 0).sort((a, b) => a - b)[0] ?? -1;
    const snippet = at < 0 ? page.description : plain(body.slice(Math.max(0, at - 60), at + 140));
    results.push({ slug: page.slug, title: page.title, score, snippet });
  }
  results.sort((a, b) => b.score - a.score || (a.slug < b.slug ? -1 : 1));
  return results.slice(0, limit);
}

/** True when llms.txt links or names the page: `(slug.md`, `(slug.md#...` or `docs/slug.md`. */
export function llmsCovers(llmsText, slug) {
  return llmsText.includes(`(${slug}.md`) || llmsText.includes(`docs/${slug}.md`);
}

function splitIndex(llmsText) {
  const start = llmsText.indexOf(INDEX_START);
  const end = llmsText.indexOf(INDEX_END);
  if (start < 0 || end < start) return { head: llmsText.replace(/\s+$/, ''), tail: '' };
  return { head: llmsText.slice(0, start).replace(/\s+$/, ''), tail: llmsText.slice(end + INDEX_END.length) };
}

/** Pages missing from the curated part of llms.txt (everything outside the generated block). */
export function uncoveredPages(llmsText, pages) {
  const { head, tail } = splitIndex(llmsText);
  const curated = `${head}\n${tail}`;
  return pages.filter((p) => !llmsCovers(curated, p.slug));
}

/** Rewrite the generated "All pages" block so every docs page appears in llms.txt. */
export function renderLlmsTxt(llmsText, pages) {
  const { head, tail } = splitIndex(llmsText);
  const missing = uncoveredPages(llmsText, pages);
  if (missing.length === 0) return `${head}${tail.replace(/^\s*$/, '')}\n`.replace(/\n{3,}/g, '\n\n');
  const lines = [
    head, '', INDEX_START, '## All pages', '',
    'Every other page under `docs/`. Each is also served as Markdown at `/docs/<path>.md` on the site.',
    '',
  ];
  for (const p of missing) lines.push(`- [${p.title}](${p.slug}.md)${p.description ? `: ${p.description}` : ''}`);
  lines.push(INDEX_END, '');
  return lines.join('\n');
}

/**
 * Bundle for agents that want everything in one fetch: the hand-written
 * copy-paste reference first, then each page under a stable heading with its URL.
 */
export function renderLlmsFull(docsDir, pages, reference) {
  const out = [reference.replace(/\s+$/, ''), '', '---', '', '# All documentation pages', '',
    `${pages.length} pages. Each section starts with its canonical Markdown URL.`, ''];
  for (const p of pages) {
    const text = readFileSync(join(docsDir, ...`${p.slug}.md`.split('/')), 'utf8').replace(/\s+$/, '');
    out.push('', `<!-- page: ${p.slug} -->`, `Source: ${docsPageUrl(p.slug)}`, '', text, '');
  }
  return out.join('\n');
}

