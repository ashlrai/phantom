/**
 * The two local real-supply signals: registry verbs no doc under docs/
 * names, and `fleet <verb>` commands README.md names that the registry
 * lacks. Every test runs the production reader against a small fixture in
 * a temp dir — no test scans the whole repo, and a source that cannot be
 * read stays `unknown`, never an empty success.
 */
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { afterEach, describe, expect, it, vi } from 'vitest';

import { cmdFleetRealSupply } from '../src/cli/fleet-real-supply.js';
import {
  collectRealSupply,
  fsRealSupplyLocalIo,
  realSupplyBriefLines,
  realSupplyLocalReader,
  type RealSupplyLocalReader,
  type RealSupplyReader,
} from '../src/core/fleet/planner-real-supply.js';

const NOW = new Date('2026-11-02T12:00:00.000Z');
const clock = () => NOW;

const REGISTRY = `// generated by scripts/gen-fleet-registry.mjs; run it after adding a verb
export const FLEET_SUBCOMMAND_LOADERS: Record<string, () => Promise<Record<string, unknown>>> = {
  'app': () => import('./fleet-app.js'),
  'bus-claim': () => import('./fleet-bus-claim.js'),
  'docs-gap': () => import('./fleet-docs-gap.js'),
  'memory': () => import('./fleet-memory.js'),
};
`;

const FLEET_VERBS_DOC = `# Fleet Verbs
| Verb | File | Reads or does | Writes anything? |
| app | \`src/cli/fleet-app.ts\` | Fixture row | no |
`;

const NESTED_DOC = `# Nested guide
The fleet memory verb reads host state.
`;

const README = `# Fixture README
Run \`phm fleet app\` to open the app, then \`ashlr fleet ghost-verb\` for ghosts.
\`phm docs --agent --json\` lists commands. The read-only fleet server never merges.
`;

const roots: string[] = [];
afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
  vi.restoreAllMocks();
});

interface FixtureFiles {
  registry?: string;
  docs?: Record<string, string>;
  readme?: string;
}

/** A small checkout fixture: registry under src/cli/, docs tree, README. */
function fixture(files: FixtureFiles): string {
  const root = mkdtempSync(join(tmpdir(), 'real-supply-signals-'));
  roots.push(root);
  if (files.registry !== undefined) {
    mkdirSync(join(root, 'src', 'cli'), { recursive: true });
    writeFileSync(join(root, 'src', 'cli', 'fleet-subcommand-registry.ts'), files.registry);
  }
  for (const [name, text] of Object.entries(files.docs ?? {})) {
    mkdirSync(join(root, 'docs', dirname(name)), { recursive: true });
    writeFileSync(join(root, 'docs', name), text);
  }
  if (files.readme !== undefined) writeFileSync(join(root, 'README.md'), files.readme);
  return root;
}

const FULL_FIXTURE: FixtureFiles = {
  registry: REGISTRY,
  docs: { 'FLEET-VERBS.md': FLEET_VERBS_DOC, 'guides/NESTED.md': NESTED_DOC },
  readme: README,
};

const okRepo = (title = 'a real issue'): RealSupplyReader =>
  async () => ({ ok: true, facts: { alerts: [], redSuite: null, issues: [{ number: 5, title }] } });

describe('realSupplyLocalReader', () => {
  it('flags registry verbs no doc names and README commands the registry lacks', async () => {
    const read = await realSupplyLocalReader(fsRealSupplyLocalIo(), fixture(FULL_FIXTURE))();
    expect(read).toEqual({
      ok: true,
      facts: {
        undocumentedVerbs: ['bus-claim', 'docs-gap'],
        readmeMissingCommands: ['ghost-verb'],
      },
    });
  });

  it('never extracts bare prose or top-level commands from README', async () => {
    const root = fixture({
      registry: REGISTRY,
      docs: { 'FLEET-VERBS.md': FLEET_VERBS_DOC },
      // `phm docs` is a top-level command and `fleet server` is prose —
      // neither is a `fleet <verb>` command the registry could carry.
      readme: 'Run `phm docs --agent --json`. The read-only fleet server never merges.',
    });
    const read = await realSupplyLocalReader(fsRealSupplyLocalIo(), root)();
    expect(read).toMatchObject({ ok: true, facts: { readmeMissingCommands: [] } });
  });

  it('stays unknown when a source cannot be read', async () => {
    const noReadme = await realSupplyLocalReader(fsRealSupplyLocalIo(), fixture({ ...FULL_FIXTURE, readme: undefined }))();
    expect(noReadme.ok).toBe(false);
    if (!noReadme.ok) expect(noReadme.reason).toContain('README.md');

    const noDocs = await realSupplyLocalReader(fsRealSupplyLocalIo(), fixture({ ...FULL_FIXTURE, docs: undefined }))();
    expect(noDocs.ok).toBe(false);
    if (!noDocs.ok) expect(noDocs.reason).toContain('docs/');

    const noRegistry = await realSupplyLocalReader(fsRealSupplyLocalIo(), fixture({ ...FULL_FIXTURE, registry: undefined }))();
    expect(noRegistry.ok).toBe(false);
    if (!noRegistry.ok) expect(noRegistry.reason).toContain('fleet-subcommand-registry.ts');
  });

  it('stays unknown on an unparseable registry rather than faking clean', async () => {
    const root = fixture({ ...FULL_FIXTURE, registry: '// generated\nexport const FLEET_SUBCOMMAND_LOADERS = {};\n' });
    const read = await realSupplyLocalReader(fsRealSupplyLocalIo(), root)();
    expect(read.ok).toBe(false);
    if (!read.ok) expect(read.reason).toContain('named no verbs');
  });

  it('stays unknown when one doc file is unreadable — never a partial scan', async () => {
    const root = fixture(FULL_FIXTURE);
    const io = {
      ...fsRealSupplyLocalIo(),
      readFile: async (path: string): Promise<string> => {
        if (path.endsWith('NESTED.md')) throw new Error('permission denied');
        return fsRealSupplyLocalIo().readFile(path);
      },
    };
    const read = await realSupplyLocalReader(io, root)();
    expect(read.ok).toBe(false);
    if (!read.ok) expect(read.reason).toContain('NESTED.md');
  });
});

describe('collectRealSupply local signals', () => {
  it('ranks local candidates after issues with exact targets', async () => {
    const supply = await collectRealSupply({
      reader: okRepo(), localRoot: fixture(FULL_FIXTURE), repos: ['ashlrai/phantom'], now: clock,
    });
    expect(supply.local).toEqual({ status: 'ok' });
    expect(supply.repos).toEqual([{ repo: 'ashlrai/phantom', status: 'ok' }]);
    expect(supply.candidates.map(c => `${c.kind}:${c.repo}:${c.target}`)).toEqual([
      'issue:ashlrai/phantom:#5',
      'undocumented-verb:ashlrai/phantom:bus-claim',
      'undocumented-verb:ashlrai/phantom:docs-gap',
      'readme-missing-command:ashlrai/phantom:fleet ghost-verb',
    ]);
    expect(supply.candidates[1]!.goal).toBe(
      'Document fleet verb "bus-claim" — it is registered but no file under docs/ names it (add its docs/FLEET-VERBS.md row)',
    );
  });

  it('marks the local source unknown on a missing README and still ranks repo supply', async () => {
    const root = fixture({ ...FULL_FIXTURE, readme: undefined });
    const supply = await collectRealSupply({
      reader: okRepo(), localRoot: root, repos: ['ashlrai/phantom'], now: clock,
    });
    expect(supply.local.status).toBe('unknown');
    expect(supply.local.reason).toContain('README.md');
    expect(supply.candidates.map(c => c.kind)).toEqual(['issue']);
    const lines = realSupplyBriefLines(supply);
    expect(lines[0]).toBe('ashlrai/phantom: Resolve issue #5: a real issue');
    expect(lines[1]).toContain('ashlrai/phantom (local): supply unread (cannot read README.md');
  });

  it('reports the local read skipped when deps turn it off', async () => {
    const supply = await collectRealSupply({ reader: okRepo(), local: false, repos: ['ashlrai/phantom'], now: clock });
    expect(supply.local).toEqual({ status: 'skipped' });
    expect(supply.candidates.map(c => c.kind)).toEqual(['issue']);
  });

  it('marks the local source unknown when an injected reader throws', async () => {
    const local: RealSupplyLocalReader = () => { throw new Error('fixture exploded'); };
    const supply = await collectRealSupply({ reader: okRepo(), local, repos: ['ashlrai/phantom'], now: clock });
    expect(supply.local.status).toBe('unknown');
    expect(supply.local.reason).toContain('fixture exploded');
  });
});

describe('cmdFleetRealSupply local signals', () => {
  it('prints local candidates and exits 0 when every source reads', async () => {
    const log = vi.spyOn(console, 'log').mockImplementation(() => {});
    const code = await cmdFleetRealSupply([], {
      reader: okRepo(), localRoot: fixture(FULL_FIXTURE), repos: ['ashlrai/phantom'], now: clock,
    });
    expect(code).toBe(0);
    const out = log.mock.calls.map(call => String(call[0])).join('\n');
    expect(out).toContain('local ok');
    expect(out).toContain('undocumented-verb');
    expect(out).toContain('fleet ghost-verb');
  });

  it('exits 1 and lists the unread local source', async () => {
    const log = vi.spyOn(console, 'log').mockImplementation(() => {});
    const local: RealSupplyLocalReader = async () => ({ ok: false, reason: 'docs dir vanished' });
    const code = await cmdFleetRealSupply([], { reader: okRepo(), local, repos: ['ashlrai/phantom'], now: clock });
    expect(code).toBe(1);
    const out = log.mock.calls.map(call => String(call[0])).join('\n');
    expect(out).toContain('local unknown');
    expect(out).toContain('docs dir vanished');
  });

  it('emits the local status in --json', async () => {
    const log = vi.spyOn(console, 'log').mockImplementation(() => {});
    const code = await cmdFleetRealSupply(['--json'], {
      reader: okRepo(), localRoot: fixture(FULL_FIXTURE), repos: ['ashlrai/phantom'], now: clock,
    });
    expect(code).toBe(0);
    const parsed = JSON.parse(String(log.mock.calls[0]![0])) as { local: { status: string }; candidates: { kind: string }[] };
    expect(parsed.local.status).toBe('ok');
    expect(parsed.candidates.map(c => c.kind)).toEqual([
      'issue', 'undocumented-verb', 'undocumented-verb', 'readme-missing-command',
    ]);
  });
});
