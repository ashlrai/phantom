/**
 * Living-docs sync: scripts/docs-sync.mjs + scripts/lib/living-docs.mjs
 * regenerate every committed file whose content the repo generates
 * (docs/cli.md, docs/CLI-REFERENCE.md, docs/llms.txt, docs/CODEMAP.md,
 * CHANGELOG.md's changelog-sync block) — the writer half that the drift
 * guards (cli-docs-drift, cli-reference-drift, codemap-drift, doc-facts)
 * already check.
 *
 * Tests run against fixture checkouts in tmp dirs. The CLI-help surfaces are
 * exercised through an injected capture (no subprocess, no real HOME); the
 * changelog surface runs the real scripts/changelog-sync.mjs on fixture
 * files, including a changelog with repeated `## [Unreleased]` milestone
 * headings like Phantom's own.
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';

// @ts-expect-error Standalone Node script has no declaration output.
import { renderCodemap, renderCodemapBlock } from '../scripts/lib/codemap.mjs';
// @ts-expect-error Standalone Node library has no declaration output.
import { syncDocs } from '../scripts/lib/living-docs.mjs';

import { syncDocs as syncDocsCore } from '../src/core/docs-sync.js';

const ROOT = resolve(__dirname, '..');
const CHANGELOG_SYNC = join(ROOT, 'scripts', 'changelog-sync.mjs');
const CODEMAP_DOC = `# Source code map

<!-- codemap:src:start -->
- \`src/old/\`
<!-- codemap:src:end -->

<!-- codemap:core:start -->
- \`src/core/old/\`
<!-- codemap:core:end -->
`;
const LLMS_DOC = `# Phantom

<!-- docs-index:start (generated by scripts/generate-docs-llms.mjs; do not edit) -->
<!-- docs-index:end -->
`;
const CHANGELOG_DOC = `# Changelog

## [Unreleased]

### Notes
- Keep this manual note.

## [1.0.0] - 2026-10-01

### Fixed
- Original fix.

## [Unreleased] — M1: Historical milestone

- Ancient entry kept for history.
`;

const roots: string[] = [];
afterEach(() => {
  for (const root of roots.splice(0)) rmSync(root, { recursive: true, force: true });
});

/** Fixture checkout: src dirs for codemap, docs dir, changelog. */
function fixtureRoot(): string {
  const root = mkdtempSync(join(tmpdir(), 'docs-sync-'));
  roots.push(root);
  for (const dir of ['src/alpha', 'src/beta', 'src/core/gamma', 'src/core/delta', 'docs']) {
    mkdirSync(join(root, dir), { recursive: true });
  }
  writeFileSync(join(root, 'docs', 'CODEMAP.md'), CODEMAP_DOC);
  writeFileSync(join(root, 'docs', 'llms.txt'), LLMS_DOC);
  writeFileSync(join(root, 'docs', 'EXTRA.md'), '# Extra\n');
  writeFileSync(join(root, 'CHANGELOG.md'), CHANGELOG_DOC);
  return root;
}

/** Deterministic fake for the real `phm` capture: distinct bytes per argv. */
function fakeCapture(outputs: Map<string, string>) {
  return (args: string[]) => {
    const key = args.join(' ');
    if (!outputs.has(key)) throw new Error(`unexpected capture ${key}`);
    return outputs.get(key)!;
  };
}

const CAPTURES = new Map([
  ['--help', 'FAKE HELP\n'],
  ['help --all', 'FAKE ALL\n'],
]);

const SNAPSHOT = {
  commits: [
    { oid: 'a'.repeat(40), message: 'feat(cli): add search' },
    { oid: 'b'.repeat(40), message: 'fix: handle empty input' },
    { oid: 'c'.repeat(40), message: 'bridge(RQ-X): BRIDGE_NOTES — RQ-X' },
  ],
  pullRequests: [
    { number: 42, title: 'feat(cli): add search', mergedAt: '2026-11-01', mergeCommit: { oid: 'a'.repeat(40) }, commits: [{ oid: 'a'.repeat(40) }] },
  ],
};

describe('codemap generation', () => {
  it('renders sorted directory inventories inside each marker pair', () => {
    const root = fixtureRoot();
    const out = renderCodemap(readFileSync(join(root, 'docs', 'CODEMAP.md'), 'utf8'), { root });
    expect(out).toContain('<!-- codemap:src:start -->\n- `src/alpha/`\n- `src/beta/`\n- `src/core/`\n<!-- codemap:src:end -->');
    expect(out).toContain('<!-- codemap:core:start -->\n- `src/core/delta/`\n- `src/core/gamma/`\n<!-- codemap:core:end -->');
  });

  it('fails closed on missing or duplicated markers', () => {
    expect(() => renderCodemapBlock('# no markers', 'src', [])).toThrow('malformed codemap:src');
    expect(() =>
      renderCodemapBlock('<!-- codemap:src:start -->\n<!-- codemap:src:start -->\n<!-- codemap:src:end -->', 'src', []),
    ).toThrow('malformed codemap:src');
  });
});

describe('syncDocs', () => {
  it('reports stale surfaces without writing in plan mode, then writes them', () => {
    const root = fixtureRoot();
    const capture = fakeCapture(CAPTURES);
    const plan = syncDocs({
      root,
      surfaces: ['cli', 'cli-reference', 'llms', 'codemap', 'changelog'],
      changelog: { snapshotData: SNAPSHOT },
      deps: { capture },
    });
    const byName = Object.fromEntries(plan.surfaces.map((s: { name: string }) => [s.name, s]));
    expect(byName['cli'].status).toBe('stale');
    expect(byName['cli-reference'].status).toBe('stale');
    expect(byName['llms'].status).toBe('stale');
    expect(byName['codemap'].status).toBe('stale');
    expect(byName['changelog'].status).toBe('stale');
    expect(plan.ok).toBe(false);
    expect(plan.proposal.title).toContain('generated documentation');
    expect(plan.proposal.body).toContain('docs/cli.md');
    // Plan mode never writes.
    expect(readFileSync(join(root, 'docs', 'CODEMAP.md'), 'utf8')).toBe(CODEMAP_DOC);

    const written = syncDocs({
      root,
      write: true,
      changelog: { snapshotData: SNAPSHOT },
      deps: { capture },
    });
    expect(written.ok).toBe(true);
    expect(written.surfaces.every((s: { status: string }) => s.status === 'written')).toBe(true);
    // Second pass is a no-op: generated content is idempotent.
    const again = syncDocs({ root, changelog: { snapshotData: SNAPSHOT }, deps: { capture } });
    expect(again.ok).toBe(true);
    expect(again.surfaces.every((s: { status: string }) => s.status === 'fresh')).toBe(true);
    expect(again.proposal).toBeNull();
  });

  it('keeps manual changelog content, inserts the sync block in the live Unreleased section', () => {
    const root = fixtureRoot();
    const report = syncDocs({
      root,
      write: true,
      surfaces: ['changelog'],
      changelog: { snapshotData: SNAPSHOT },
      deps: { capture: fakeCapture(CAPTURES) },
    });
    expect(report.surfaces[0].status).toBe('written');
    const next = readFileSync(join(root, 'CHANGELOG.md'), 'utf8');
    expect(next).toContain('Keep this manual note.');
    expect(next).toContain('<!-- changelog-sync:start -->');
    expect(next).toContain('**cli:** add search (#42)');
    expect(next).toContain('handle empty input');
    expect(next).not.toContain('BRIDGE_NOTES');
    // The generated block lands in the first Unreleased section, before the
    // historical `## [Unreleased] — M1` milestone — the duplicate heading that
    // used to make changelog-sync refuse this file entirely.
    expect(next.indexOf('changelog-sync:start')).toBeLessThan(next.indexOf('M1: Historical'));
    expect(next).toContain('## [Unreleased] — M1');
  });

  it('reports the changelog surface skipped when no snapshot, base or tag exists', () => {
    const root = fixtureRoot();
    const report = syncDocs({
      root,
      surfaces: ['changelog'],
      changelog: {},
      deps: { capture: fakeCapture(CAPTURES) },
    });
    expect(report.surfaces[0].status).toBe('skipped');
    expect(report.surfaces[0].detail).toContain('--changelog');
  });

  it('marks a surface error when its generator fails', () => {
    const root = fixtureRoot();
    writeFileSync(join(root, 'docs', 'CODEMAP.md'), '# broken, no markers\n');
    const report = syncDocs({ root, surfaces: ['codemap'], deps: { capture: fakeCapture(CAPTURES) } });
    expect(report.surfaces[0].status).toBe('error');
    expect(report.ok).toBe(false);
    expect(report.surfaces[0].detail).toContain('codemap');
  });

  it('rejects unknown surface names', () => {
    expect(() => syncDocs({ root: fixtureRoot(), surfaces: ['bogus'] })).toThrow('unknown surface');
  });

  it('keeps changelog-sync verify strict: a duplicated release section still fails', () => {
    const home = mkdtempSync(join(tmpdir(), 'docs-sync-verify-'));
    roots.push(home);
    const changelog = join(home, 'CHANGELOG.md');
    const snapshot = join(home, 'snapshot.json');
    writeFileSync(
      changelog,
      '# Changelog\n\n## [Unreleased]\n\n## [1.0.0] - 2026-10-01\n\n- a.\n\n## [1.0.0] - 2026-10-02\n\n- b.\n',
    );
    writeFileSync(
      snapshot,
      JSON.stringify({ tags: ['v1.0.0'], releases: [{ tagName: 'v1.0.0', isDraft: false, body: '- a.' }] }),
    );
    expect(() =>
      execFileSync(process.execPath, [CHANGELOG_SYNC, 'verify', '--snapshot', snapshot, '--changelog', changelog], { encoding: 'utf8' }),
    ).toThrow(/Release mismatch/);
  });
});

describe('living docs drift guard (this checkout)', () => {
  it('codemap and llms surfaces are fresh in the committed tree', () => {
    const report = syncDocs({ root: ROOT, surfaces: ['codemap', 'llms'], deps: { capture: fakeCapture(CAPTURES) } });
    expect(
      report.surfaces.map((s: { name: string; status: string }) => `${s.name}:${s.status}`),
      'run: node --import tsx scripts/docs-sync.mjs --write',
    ).toEqual(['llms:fresh', 'codemap:fresh']);
  });
});

// --- core docs-sync (docs-sync.toml engine) ---

function fixture(): string {
  const root = mkdtempSync(join(tmpdir(), 'docs-sync-')); roots.push(root);
  mkdirSync(join(root, 'docs'));
  writeFileSync(join(root, 'docs-sync.toml'), `version = 1\nname = "example"\ndocsDir = "docs"\nagentsFile = "AGENTS.md"\nllmsFile = "docs/llms.txt"\nllmsFullFile = "docs/llms-full.txt"\nllmsReferenceFile = "docs/reference.txt"\nhostedDir = "site/docs"\nregistry = "configured"\ncliName = "example"\nsiteOrigin = "https://example.com"\ncommands = ["status"]\n`);
  writeFileSync(join(root, 'AGENTS.md'), '# Agents\n');
  writeFileSync(join(root, 'docs/llms.txt'), '# Index\n');
  writeFileSync(join(root, 'docs/reference.txt'), '# Reference\n');
  writeFileSync(join(root, 'docs/status.md'), '# status\n\nInspect status.\n\n```sh\nexample status --json\n```\n');
  return root;
}
describe('docs sync', () => {
  it('writes deterministic outputs and detects changes without writing in check mode', () => {
    const root = fixture();
    expect(syncDocsCore(root, undefined, false).ok).toBe(true);
    expect(syncDocsCore(root, undefined, true)).toMatchObject({ ok: true, drift: [], missing: [] });
    const before = readFileSync(join(root, 'docs/llms.txt'), 'utf8');
    writeFileSync(join(root, 'docs/new.md'), '# New\n');
    const result = syncDocsCore(root, undefined, true);
    expect(result.ok).toBe(false);
    expect(result.drift).toContain('docs/llms.txt');
    expect(readFileSync(join(root, 'docs/llms.txt'), 'utf8')).toBe(before);
    expect(readFileSync(join(root, 'docs/llms-full.txt'), 'utf8')).toContain('https://example.com/docs/status.md');
  });
  it('reports missing section and real shell example independently', () => {
    const root = fixture();
    writeFileSync(join(root, 'docs/status.md'), '# Overview\n\n```text\nexample status\n```\n');
    expect(syncDocsCore(root, undefined, false).missing).toEqual([{ command: 'status', section: false, example: false }]);
  });
  it('rejects paths outside the checkout', () => {
    const root = fixture();
    const path = join(root, 'docs-sync.toml');
    writeFileSync(path, readFileSync(path, 'utf8').replace('agentsFile = "AGENTS.md"', 'agentsFile = "../outside"'));
    expect(() => syncDocsCore(root, undefined, false)).toThrow(/outside checkout/);
  });
  it('a fence with another info string does not hide the following shell block', () => {
    const root = fixture();
    writeFileSync(join(root, 'docs/status.md'), '# status\n\nInspect status.\n\n```toml\nkey = "value"\n```\n\n```sh\nexample status --json\n```\n');
    expect(syncDocsCore(root, undefined, false).ok).toBe(true);
    expect(syncDocsCore(root, undefined, true)).toMatchObject({ ok: true, missing: [] });
  });
});
