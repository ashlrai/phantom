/**
 * shipped-page.ts: the website's "What shipped" page. `phm shipped --site`
 * writes one report to site/shipped.json and this rendering of it to
 * site/shipped.html, so the page is plain HTML with no script and no runtime
 * calls. Pure: the same report always gives the same page.
 */
import { SHIPPED_SCHEMA, shippedSummary, type ShippedReport } from './shipped.js';

export const SHIPPED_SITE_JSON = 'site/shipped.json';
export const SHIPPED_SITE_PAGE = 'site/shipped.html';
/** The page lists this many of the newest changes; the report keeps up to this many per area so none of them is cut early. */
export const SHIPPED_SITE_ITEMS = 30;

const escape = (text: string) => text.replace(/[&<>"']/g, char => `&#${char.charCodeAt(0)};`);
const STYLE = '*{box-sizing:border-box}body{margin:0;background:#f2f4f8;color:#101b29;font:16px/1.6 system-ui,sans-serif}main,header,footer{max-width:820px;margin:auto;padding:1.5rem}'
  + 'a{color:#4338ca}a:focus-visible{outline:3px solid #4338ca;outline-offset:4px}header{display:flex;justify-content:space-between;gap:1rem}header a{font-weight:700;text-decoration:none}'
  + 'h1{font-size:clamp(2.2rem,6vw,3.4rem);line-height:1.05;margin:2rem 0 1rem}.lead{font-size:1.25rem}.muted,time,.ref{color:#4f5d70}ol{list-style:none;padding:0}'
  + 'li{background:#fff;border:1px solid #d8dee9;border-radius:8px;padding:.8rem 1rem;margin:.6rem 0}time,.ref{font-size:.875rem}'
  + '.area{font-size:.75rem;font-weight:700;text-transform:uppercase;letter-spacing:.04em;color:#4338ca;margin:0 .6rem}p.item{margin:.2rem 0 0}';

/** The newest changes across every area, newest first. */
export function shippedItems(report: ShippedReport, limit = SHIPPED_SITE_ITEMS) {
  return report.areas.flatMap(area => area.lines.map(line => ({ ...line, area: area.label })))
    .sort((a, b) => a.mergedAt < b.mergedAt ? 1 : a.mergedAt > b.mergedAt ? -1 : (b.number ?? 0) - (a.number ?? 0)).slice(0, limit);
}

export function shippedPage(report: ShippedReport): string {
  const [headline, ...rest] = shippedSummary(report);
  const items = shippedItems(report);
  const listed = report.areas.reduce((sum, area) => sum + area.count, 0);
  const list = items.length === 0 ? '<p class="muted">Nothing shipped yet this week.</p>' : `<ol>\n${items.map(item => {
    const ref = [item.repo ?? '', ...item.prs.map(number => `#${number}`)].filter(Boolean).join(' ');
    return `<li><time datetime="${escape(item.mergedAt)}">${escape(item.mergedAt.slice(0, 10))}</time><span class="area">${escape(item.area)}</span>${ref ? `<span class="ref">${escape(ref)}</span>` : ''}<p class="item">${escape(item.text)}</p></li>`;
  }).join('\n')}\n</ol>${listed > items.length ? `\n<p class="muted">Showing the newest ${items.length} of ${listed} changes.</p>` : ''}`;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="What shipped across the Ashlr repositories: recent user-facing changes in plain words, by product area.">
<link rel="canonical" href="https://verse.ashlr.ai/shipped">
<link rel="icon" href="/assets/phantom-mark.svg" type="image/svg+xml">
<title>What shipped | Phantom</title>
<!-- generated by phm shipped --site (${SHIPPED_SCHEMA}); do not edit by hand -->
<style>${STYLE}</style>
</head>
<body>
<header><a href="/">Phantom</a><a href="https://github.com/ashlrai/phantom/blob/master/docs/SHIPPED.md">Docs page</a></header>
<main>
<h1>What shipped</h1>
<p class="lead">${escape(headline!)}</p>
${rest.map(line => `<p class="muted">${escape(line)}</p>\n`).join('')}${list}
</main>
<footer class="muted">Updated ${escape(report.generatedAt.slice(0, 10))}, covering the last ${report.days} ${report.days === 1 ? 'day' : 'days'}. The same data as <a href="shipped.json">shipped.json</a> and <code>phm shipped --json</code>. <a href="/">Phantom home</a></footer>
</body></html>
`;
}
