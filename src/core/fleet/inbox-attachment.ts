import { mkdir, open } from 'node:fs/promises';
import { join } from 'node:path';

/** Hard bound on a stored long message (characters). Longer input is rejected before any write. */
export const INBOX_ATTACH_MAX_CHARS = 64_000;
/** Characters of a long message kept inline in MASON-INBOX.md ahead of the pointer. */
export const INBOX_ATTACH_SUMMARY_CHARS = 1500;

const ATTACH_DIR = 'leader/inbox-attachments';
const ID_PATTERN = /^[A-Za-z0-9._:-]{1,64}$/;
const POINTER_PATTERN = /\s*\[full text: (leader\/inbox-attachments\/[A-Za-z0-9._:-]{1,64}\.md), \d+ chars\]$/;

function checkId(id: string): void {
  if (!ID_PATTERN.test(id) || id === '.' || id === '..') throw new Error('Invalid inbox attachment id');
}

/** Relative pointer path for an entry id. The id is generated by the inbox, never caller supplied. */
export function inboxAttachmentRelPath(id: string): string {
  checkId(id);
  return `${ATTACH_DIR}/${id}.md`;
}

export function inboxAttachmentPath(runsDir: string, id: string): string {
  return join(runsDir, inboxAttachmentRelPath(id));
}

/** Inline summary (cut at a word boundary) followed by a compact, parseable pointer. */
export function summariseForInbox(text: string, limit: number, id: string, originalLength = text.length): string {
  const prefix = text.slice(0, limit);
  const whitespace = prefix.search(/\s+\S*$/);
  const summary = (whitespace > 0 ? prefix.slice(0, whitespace) : prefix).trimEnd();
  return `${summary} … [full text: ${inboxAttachmentRelPath(id)}, ${originalLength} chars]`;
}

/**
 * Read the pointer back from an entry body. Only a trailing pointer whose path is
 * exactly the entry's own id is trusted, so message text cannot aim at another file.
 */
export function parseInboxAttachmentPointer(body: string, entryId: string | undefined): string | undefined {
  if (!entryId || !ID_PATTERN.test(entryId)) return undefined;
  const found = POINTER_PATTERN.exec(body)?.[1];
  return found === inboxAttachmentRelPath(entryId) ? found : undefined;
}

/** Exclusive create (`wx`, private mode): an existing attachment is never overwritten; EEXIST propagates. */
export async function writeInboxAttachment(runsDir: string, id: string, text: string): Promise<void> {
  const path = inboxAttachmentPath(runsDir, id);
  await mkdir(join(runsDir, ATTACH_DIR), { recursive: true, mode: 0o700 });
  const handle = await open(path, 'wx', 0o600);
  try {
    await handle.writeFile(text, 'utf8');
  } finally {
    await handle.close();
  }
}
