import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ashlrHome } from '../cloud/store.js';
import type { ModelModeTier } from '../run/model-mode-data.js';
import { MODEL_MODE_TIERS, MODEL_CATALOG_UNASSIGNED, MODEL_CATALOG_UNSEEN } from '../run/model-catalog-data.js';
import { MODEL_CATALOG_PATTERNS, type CatalogPattern } from '../run/model-catalog-patterns.js';
import { collectCatalogSources, type CatalogSource, type CatalogSourceDeps } from './catalog-sources.js';

export interface CatalogData { tiers: Readonly<Record<string, ModelModeTier>>; unassigned: readonly string[]; unseen: Readonly<Record<string, string>> }
const sorted = <T>(obj: Readonly<Record<string, T>>): Record<string, T> => Object.fromEntries(Object.entries(obj).sort(([a], [b]) => a.localeCompare(b)));
export function renderCatalog(data: CatalogData): string {
  return `/** Generated by \`phm router catalog refresh --apply\`; data only. */\nimport type { ModelModeTier } from './model-mode-data.js';\n\nexport const MODEL_MODE_TIERS: Readonly<Record<string, ModelModeTier>> = ${JSON.stringify(sorted(data.tiers), null, 2)};\n\nexport const MODEL_CATALOG_UNASSIGNED: readonly string[] = ${JSON.stringify([...data.unassigned].sort(), null, 2)};\n\nexport const MODEL_CATALOG_UNSEEN: Readonly<Record<string, string>> = ${JSON.stringify(sorted(data.unseen), null, 2)};\n`;
}

export function diffCatalog(current: CatalogData, sources: CatalogSource[], patterns: readonly CatalogPattern[], now: string, dryRun = true) {
  const rejectedRules: { rule: string; reason: string }[] = [];
  const rules = patterns.flatMap(row => {
    try {
      if (!Array.isArray(row.sources) || !row.sources.length || row.sources.some(s => typeof s !== 'string' || !s)) throw new Error();
      const regex = new RegExp(row.pattern);
      const validTier = row.tier === undefined || row.tier === 'lite' || row.tier === 'normal';
      if (!validTier) rejectedRules.push({ rule: row.pattern, reason: 'Only lite and normal may be assigned automatically' });
      return [{ ...row, regex, tier: validTier ? row.tier : undefined }];
    } catch { rejectedRules.push({ rule: row.pattern, reason: 'Invalid pattern or sources' }); return []; }
  });
  const seen = new Map<string, string[]>();
  for (const source of sources.filter(s => s.status === 'ok')) for (const model of source.models) seen.set(model, [...(seen.get(model) ?? []), source.id]);
  const tiers = { ...current.tiers }; const unassigned = new Set(current.unassigned); const unseen = { ...current.unseen };
  const additions: { model: string; tier: 'lite' | 'normal' | 'unassigned'; rule: string | null; sources: string[] }[] = [];
  const reappeared: string[] = []; const unknown: { model: string; reason: string }[] = [];
  const catalog = new Set([...Object.keys(tiers), ...unassigned]);
  for (const model of [...seen.keys()].sort()) {
    if (unseen[model]) { reappeared.push(model); delete unseen[model]; }
    if (catalog.has(model)) continue;
    const rule = rules.find(r => r.regex.test(model));
    const tier = rule?.tier ?? 'unassigned';
    additions.push({ model, tier, rule: rule?.pattern ?? null, sources: seen.get(model)!.sort() });
    if (tier === 'unassigned') unassigned.add(model); else tiers[model] = tier;
  }
  for (const model of [...catalog].sort()) {
    if (seen.has(model)) continue;
    const rule = rules.find(r => r.regex.test(model));
    if (!rule || rule.sources.some(id => !sources.some(s => s.id === id && s.status === 'ok'))) {
      unknown.push({ model, reason: rule ? 'Owning source unavailable' : 'No owning source pattern' });
      continue;
    }
    unseen[model] ??= now;
  }
  const missing = Object.entries(sorted(unseen)).map(([model, unseenSince]) => ({ model, unseenSince }));
  const older = (days: number) => missing.filter(m => Date.parse(now) - Date.parse(m.unseenSince) > days * 86400_000);
  return {
    report: { schema: 'router.catalog-refresh.v1' as const, generatedAt: now, dryRun, sources, additions, reappeared, unseen: missing, deprecations: older(30), proposedRemovals: older(90), unknown, rejectedRules },
    data: { tiers, unassigned: [...unassigned].sort(), unseen },
  };
}

export function catalogPatch(before: string, after: string): string {
  if (before === after) return '';
  const a = before.trimEnd().split('\n'); const b = after.trimEnd().split('\n');
  return `--- a/src/core/run/model-catalog-data.ts\n+++ b/src/core/run/model-catalog-data.ts\n@@ -1,${a.length} +1,${b.length} @@\n${a.map(l => '-' + l).join('\n')}\n${b.map(l => '+' + l).join('\n')}\n`;
}

export async function refreshCatalog(opts: { apply?: boolean; includeSeats?: boolean; outDir?: string; catalog?: string } = {}, deps: { sources?: CatalogSource[]; sourceDeps?: Partial<CatalogSourceDeps>; current?: CatalogData; now?: string } = {}) {
  const current = deps.current ?? { tiers: MODEL_MODE_TIERS, unassigned: MODEL_CATALOG_UNASSIGNED, unseen: MODEL_CATALOG_UNSEEN };
  const sources = deps.sources ?? await collectCatalogSources(opts.includeSeats, deps.sourceDeps);
  const now = deps.now ?? new Date().toISOString();
  const { report, data } = diffCatalog(current, sources, MODEL_CATALOG_PATTERNS, now, !opts.apply);
  const catalog = opts.catalog ?? fileURLToPath(new URL('../../../src/core/run/model-catalog-data.ts', import.meta.url));
  const before = await readFile(catalog, 'utf8'); const after = renderCatalog(data);
  const dir = opts.outDir ?? join(ashlrHome(), 'router', 'catalog');
  await mkdir(dir, { recursive: true });
  const stem = join(dir, `catalog-refresh-${now.replace(/[:.]/g, '-')}`);
  await writeFile(stem + '.json', JSON.stringify(report, null, 2) + '\n');
  await writeFile(stem + '.patch', catalogPatch(before, after));
  if (opts.apply && before !== after) await writeFile(catalog, after);
  return report;
}
